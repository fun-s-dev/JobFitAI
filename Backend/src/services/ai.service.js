const { GoogleGenAI } = require("@google/genai")
const { z } = require("zod")
const { createInterviewReportService } = require("../v2/services/interviewReport.service")

/**
 * Strips $schema and additionalProperties keys that the Gemini API rejects.
 */
function cleanSchemaForGemini(schema) {
    const copy = JSON.parse(JSON.stringify(schema))
    function strip(obj) {
        if (obj && typeof obj === "object") {
            delete obj["$schema"]
            delete obj["additionalProperties"]
            for (const val of Object.values(obj)) strip(val)
        }
    }
    strip(copy)
    return copy
}
const puppeteer = require("puppeteer")

// Legacy direct client: now used ONLY by generateResumePdf below, which is scheduled for removal
// once the V2 grounded export has been verified. The interview report goes through llmClient.
const ai = new GoogleGenAI({
    apiKey: process.env.GOOGLE_GENAI_API_KEY
})

// Interview report generation lives in the V2-style service so that it shares the llmClient
// (timeout, retry, pacing, Zod validation with a repair attempt, llmcalls audit rows for budgets).
const defaultInterviewReportService = createInterviewReportService()
let activeInterviewReportService = defaultInterviewReportService

/** Test hook (same pattern as setDraftService): inject a service built on a fake Gemini SDK object. */
function setInterviewReportService(service) {
    activeInterviewReportService = service || defaultInterviewReportService
}

/**
 * @description Generates the interview preparation report. Throws on upstream failure
 * (callers map LlmValidationError / QuotaExhaustedError / transient errors to HTTP statuses).
 */
async function generateInterviewReport({ resume, selfDescription, jobDescription, user, requestId }) {
    return activeInterviewReportService.generateInterviewReport({
        resume,
        selfDescription,
        jobDescription,
        user,
        requestId,
    })
}



async function generatePdfFromHtml(htmlContent) {
    const browser = await puppeteer.launch()
    const page = await browser.newPage();
    await page.setContent(htmlContent, { waitUntil: "networkidle0" })

    const pdfBuffer = await page.pdf({
        format: "A4", margin: {
            top: "20mm",
            bottom: "20mm",
            left: "15mm",
            right: "15mm"
        }
    })

    await browser.close()

    return pdfBuffer
}

async function generateResumePdf({ resume, selfDescription, jobDescription }) {

    const resumePdfSchema = z.object({
        html: z.string().describe("The HTML content of the resume which can be converted to PDF using any library like puppeteer")
    })

    const prompt = `Generate resume for a candidate with the following details:
                        Resume: ${resume}
                        Self Description: ${selfDescription}
                        Job Description: ${jobDescription}

                        the response should be a JSON object with a single field "html" which contains the HTML content of the resume which can be converted to PDF using any library like puppeteer.
                        The resume should be tailored for the given job description and should highlight the candidate's strengths and relevant experience. The HTML content should be well-formatted and structured, making it easy to read and visually appealing.
                        The content of resume should be not sound like it's generated by AI and should be as close as possible to a real human-written resume.
                        you can highlight the content using some colors or different font styles but the overall design should be simple and professional.
                        The content should be ATS friendly, i.e. it should be easily parsable by ATS systems without losing important information.
                        The resume should not be so lengthy, it should ideally be 1-2 pages long when converted to PDF. Focus on quality rather than quantity and make sure to include all the relevant information that can increase the candidate's chances of getting an interview call for the given job description.
                    `

    try {
        const response = await ai.models.generateContent({
            model: process.env.GEMINI_MODEL || "gemini-3.5-flash-lite",
            contents: prompt,
            config: {
                responseMimeType: "application/json",
                responseSchema: cleanSchemaForGemini(z.toJSONSchema(resumePdfSchema)),
            }
        })

        const jsonContent = JSON.parse(response.text)

        const pdfBuffer = await generatePdfFromHtml(jsonContent.html)

        return pdfBuffer
    } catch (error) {
        console.error("ERROR:", error)
        console.error(error.stack)
        throw error
    }

}

